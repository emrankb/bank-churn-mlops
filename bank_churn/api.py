"""FastAPI churn prediction using a locally trained, trusted model artifact.

Requests contain feature values only: never customer IDs, names, or labels.
The service does not log request bodies or persist customer predictions.
"""
from __future__ import annotations

import os
from pathlib import Path

import joblib
import pandas as pd
from fastapi import FastAPI
from pydantic import BaseModel, ConfigDict, Field, StrictInt

from .data import CATEGORICAL, NUMERIC


class ChurnFeatures(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)

    CreditScore: int = Field(ge=0, le=1000)
    Geography: str = Field(min_length=1, max_length=80)
    Gender: str = Field(min_length=1, max_length=80)
    Age: int = Field(gt=0, le=120)
    Tenure: int = Field(ge=0, le=100)
    Balance: float = Field(ge=0, allow_inf_nan=False)
    NumOfProducts: int = Field(ge=1, le=100)
    HasCrCard: StrictInt = Field(ge=0, le=1)
    IsActiveMember: StrictInt = Field(ge=0, le=1)
    EstimatedSalary: float = Field(ge=0, allow_inf_nan=False)


class ChurnPrediction(BaseModel):
    churn_prediction: int = Field(ge=0, le=1)
    churn_probability: float = Field(ge=0, le=1)


def load_trusted_model(path: str | Path):
    """Load only a model generated by the local training pipeline.

    joblib is pickle-backed: never load user-uploaded or untrusted files.
    """
    source = Path(path).expanduser().resolve()
    if not source.is_file():
        raise RuntimeError("Trained model not found; run training locally first.")
    model = joblib.load(source)
    if not all(hasattr(model, method) for method in ("predict", "predict_proba")):
        raise RuntimeError("Saved model lacks prediction methods.")
    return model


def create_app(*, model=None, model_path: str | Path | None = None) -> FastAPI:
    """Create the service with a fixed fitted pipeline loaded only once."""
    if model is None:
        source = model_path or os.environ.get(
            "CHURN_MODEL_PATH", "artifacts/churn-model/model.joblib"
        )
        model = load_trusted_model(source)
    app = FastAPI(
        title="Bank Churn Prediction API",
        version="1.0.0",
        docs_url="/docs",
        redoc_url=None,
    )

    @app.get("/health")
    def health() -> dict:
        return {"status": "ready", "model_loaded": True}

    @app.post("/predict", response_model=ChurnPrediction)
    def predict(payload: ChurnFeatures) -> ChurnPrediction:
        values = payload.model_dump()
        # Column order is the training contract; identifiers and surname
        # cannot enter the request thanks to extra="forbid".
        row = pd.DataFrame([values], columns=[*NUMERIC, *CATEGORICAL])
        predicted = int(model.predict(row)[0])
        probabilities = model.predict_proba(row)[0]
        labels = list(model.classes_)
        if 1 not in labels or predicted not in (0, 1):
            raise RuntimeError("Model has an invalid binary class contract.")
        probability = float(probabilities[labels.index(1)])
        return ChurnPrediction(
            churn_prediction=predicted,
            churn_probability=probability,
        )

    return app
